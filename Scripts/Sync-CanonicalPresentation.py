"""Copy approved original assets and emit presentation data; never edit the source game."""
import argparse
import hashlib
import json
import shutil
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument('--source', type=Path, required=True)
args = parser.parse_args()
root = Path(__file__).resolve().parents[1]
source = args.source.resolve()
fixture = json.loads((source / 'docs/parity/golden_fixtures.json').read_text(encoding='utf-8'))
assets = source / 'public/assets'
content = root / 'Content/RuaDeAco'
records = []

def copy(src, dst):
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(src, dst)
    digest = hashlib.sha256(src.read_bytes()).hexdigest()
    assert hashlib.sha256(dst.read_bytes()).hexdigest() == digest
    records.append({'source': src.relative_to(source).as_posix(), 'target': dst.relative_to(root).as_posix(), 'sha256': digest})

folders = {'guto-barba': 'GutoBarba', 'rafa-mare': 'RafaMare', 'noir-reflexo': 'NoirReflexo', 'astro-riso': 'AstroRiso', 'dante-sinal': 'DanteSinal', 'leo-violeta': 'LeoVioleta'}
stage_folders = {'cais-da-cidade': 'CaisDaCidade', 'cozinha-macabra': 'CozinhaMacabra', 'sitio': 'Sitio'}
for fighter, folder in folders.items():
    for src in (assets / 'fighters' / fighter).glob('*.png'):
        copy(src, content / 'Art/Characters' / folder / src.name)
for src in (assets / 'portraits').glob('*.png'):
    copy(src, content / 'Art/Portraits' / src.name)
for stage, folder in stage_folders.items():
    for src in (assets / 'stages' / stage).rglob('*.png'):
        rel = src.relative_to(assets / 'stages' / stage)
        if rel.parts[0] == 'remaster': rel = Path(*rel.parts[1:])
        copy(src, content / 'Art/Environments' / folder / rel)
for src in (assets / 'ui').rglob('*.png'):
    copy(src, content / 'Art/UI' / src.relative_to(assets / 'ui'))
for kind in ('music', 'sfx'):
    for src in (assets / 'audio' / kind).rglob('*.ogg'):
        copy(src, content / 'Audio' / ('Music' if kind == 'music' else 'Sfx') / src.relative_to(assets / 'audio' / kind))
for src in (assets / 'fonts').glob('*'):
    if src.is_file(): copy(src, content / 'Fonts' / src.name)

def quote(value): return json.dumps(value, ensure_ascii=True)
def fp(value): return repr(float(value)) + 'f'
rows, phases, effects = [], [], []
for fighter in fixture['presentation']['fighterSprites']:
    fid = fighter['fighterId']
    for aid, anim in fighter['animations'].items():
        offset = anim.get('visualOffset', {'x': 0, 'y': 0})
        path = Path(anim['path']).name
        rows.append('{' + ','.join([quote(fid), quote(aid), quote(path), str(anim['frameWidth']), str(anim['frames']), str(anim['frameRate']), 'true' if anim['repeat'] == -1 else 'false', fp(offset['x']), fp(offset['y']), fp(fighter['visualOffset']['y'])]) + '}')
    for move, entries in fighter.get('movePhases', {}).items():
        for phase in entries:
            phases.append('{' + ','.join([quote(fid), quote(move), quote(phase['animation']), str(phase['range']['from']), str(phase['range']['to']), str(phase.get('explicitFrame', -1))]) + '}')
    for effect in fighter.get('effects', []):
        active = effect.get('activeRange', {'from': 0, 'to': 100000})
        effects.append('{' + ','.join([quote(fid), quote(effect['moveId']), quote(Path(effect['path']).name), quote(effect['usage']), str(effect['frameWidth']), str(effect['frames']), str(effect['frameRate']), str(active['from']), str(active['to']), fp(effect['offset']['x']), fp(effect['offset']['y']), fp(effect['scale'])]) + '}')
header = '// Generated by Scripts/Sync-CanonicalPresentation.py from the original TypeScript fixture.\n#pragma once\nnamespace CanonicalVisual {\n'
header += 'struct Animation { const char *fighter, *id, *file; int size, frames, fps; bool loop; float x, y, sole; };\ninline constexpr Animation animations[] = {\n' + ',\n'.join(rows) + '\n};\n'
header += 'struct Phase { const char *fighter, *move, *animation; int from, to, frame; };\ninline constexpr Phase phases[] = {\n' + ',\n'.join(phases) + '\n};\n'
header += 'struct Effect { const char *fighter, *move, *file, *usage; int size, frames, fps, from, to; float x, y, scale; };\ninline constexpr Effect effects[] = {\n' + ',\n'.join(effects) + '\n};\n}\n'
sounds = []
for fid, moves in fixture['presentation']['specialSounds'].items():
    for mid, sound in moves.items():
        sounds.append('{' + ','.join([quote(fid),quote(mid),quote(sound['voice']+'.ogg'),quote(sound['effect']+'.ogg'),fp(sound.get('rate',1)),fp(fixture['presentation']['samples'][sound['voice']]['gain']),fp(fixture['presentation']['samples'][sound['effect']]['gain'])]) + '}')
header += 'namespace CanonicalVisual { struct SoundCue { const char *fighter, *move, *voice, *effect; float rate, voiceGain, effectGain; };\ninline constexpr SoundCue sounds[] = {\n' + ',\n'.join(sounds) + '\n};\n}\n'
(root / 'Source/Prototype/CanonicalPresentation.h').write_text(header, encoding='utf-8')
(root / 'Data/generated/presentation-provenance.json').write_text(json.dumps({'sourceRepository': fixture['sourceRepository'], 'files': records}, indent=2) + '\n', encoding='utf-8')
print(f'Canonical presentation synchronized: {len(records)} files, {len(rows)} animations, {len(phases)} move phases, {len(effects)} effects; hashes verified.')
